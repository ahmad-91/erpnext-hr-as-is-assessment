function mq(
  id: string,
  text: string,
  helpText: string,
  dimension: Question["dimension"] = "process"
): Question {
  return {
    id,
    dimension,
    text,
    type: "single",
    required: true,
    options: WO_MATURITY,
    helpText,
  };
}

